def _slugify(value: Any, *, fallback: str = "study") -> str:
    text = str(value or "").strip().lower()
    text = re.sub(r"[^a-z0-9]+", "_", text)
    text = re.sub(r"_+", "_", text).strip("_")
    if not text:
        text = fallback
    if text[0].isdigit():
        text = f"study_{text}"
    return text[:STUDY_ID_MAX_LEN].rstrip("_") or fallback


def _default_study_id(payload: Dict[str, Any], json_path: Path) -> str:
    candidate = payload.get("study_id") or payload.get("paper_id")
    if not candidate:
        stem = json_path.stem
        stem = re.sub(r"_stage[0-9]+_(?:extraction|filter|patched)$", "", stem)
        candidate = stem
    slug = _slugify(candidate)
    return slug if slug.startswith("study_") else f"study_{slug}"


def paper_local_stage4_dir(json_path: Path, study_id: Optional[str] = None) -> Path:
    """Default local Stage 4 package directory for a paper output folder."""
    json_path = Path(json_path)
    if study_id:
        resolved_study_id = study_id
    else:
        payload = json.loads(json_path.read_text(encoding="utf-8"))
        resolved_study_id = _default_study_id(payload, json_path)
    return json_path.parent / "stage4" / resolved_study_id


