def _runtime_material_issues(material: Dict[str, Any]) -> List[str]:
    issues: List[str] = []
    instructions = material.get("instructions") or material.get("stimulus")
    items = material.get("items")
    if not isinstance(instructions, str) or not instructions.strip():
        issues.append("missing_instructions")
    if material.get("material_id") and not str(material.get("question") or "").strip():
        issues.append("missing_response_question")
    if not isinstance(items, list):
        issues.append("items_not_list")
        return issues
    if not items:
        issues.append("missing_response_items")
        return issues
    for idx, item in enumerate(items, start=1):
        if not isinstance(item, dict):
            issues.append(f"item_{idx}_not_object")
            continue
        question = item.get("question")
        if not isinstance(question, str) or not question.strip():
            issues.append(f"item_{idx}_missing_question")
        item_type = str(item.get("type") or "").strip().lower()
        options = item.get("options") if isinstance(item.get("options"), list) else []
        scale = item.get("scale") if isinstance(item.get("scale"), dict) else {}
        matrix = item.get("matrix") if isinstance(item.get("matrix"), dict) else {}
        response_format = item.get("response_format") if isinstance(item.get("response_format"), dict) else {}
        if not response_format and isinstance(material.get("response_format"), dict):
            response_format = material["response_format"]
        has_scale = bool(
            (scale.get("min") is not None and scale.get("max") is not None)
            or response_format.get("scale_min") is not None
            or response_format.get("scale_max") is not None
        )
        has_matrix = bool(
            (matrix.get("rows") and matrix.get("columns"))
            or (response_format.get("rows") and response_format.get("columns"))
        )
        if item_type in {"multiple_choice", "likert", "scale", "slider", "ranking"} and not (options or has_scale):
            issues.append(f"item_{idx}_missing_options")
        if item_type == "matrix" and not has_matrix:
            issues.append(f"item_{idx}_missing_matrix_contract")
    return issues


def _normalized_contract_text(value: Any) -> str:
    return re.sub(r"\s+", " ", str(value or "")).strip()


def _participant_item_signature(item: Dict[str, Any]) -> str:
    payload = {
        "question": _normalized_contract_text(item.get("question")),
        "type": str(item.get("type") or "").strip().lower(),
        "options": item.get("options") if isinstance(item.get("options"), list) else [],
        "scale": item.get("scale") if isinstance(item.get("scale"), dict) else {},
        "matrix": item.get("matrix") if isinstance(item.get("matrix"), dict) else {},
        "response_format": item.get("response_format") if isinstance(item.get("response_format"), dict) else {},
    }
    return json.dumps(payload, ensure_ascii=False, sort_keys=True)


def _material_derivation_contract(
    runtime: Dict[str, Any],
    source: Optional[Dict[str, Any]],
) -> Dict[str, Any]:
    """Verify that runtime participant content is derived from Stage 3 evidence.

    This is deliberately language-independent. It checks data lineage and exact
    content preservation instead of maintaining a phrase blacklist.
    """
    issues: List[str] = []
    source = source if isinstance(source, dict) else None
    if source is None:
        return {
            "valid": False,
            "source_ready": False,
            "source_primary": None,
            "issues": ["missing_stage3_source_material"],
        }

    source_readiness = source.get("readiness") if isinstance(source.get("readiness"), dict) else {}
    source_ready = source_readiness.get("ready") is True
    if not source_ready:
        issues.append("stage3_source_material_not_ready")

    source_trace = source.get("source_trace") if isinstance(source.get("source_trace"), dict) else {}
    source_primary = source_trace.get("primary_source")
    if not source_primary:
        issues.append("missing_stage3_source_provenance")
    elif source_primary in NON_PARTICIPANT_SOURCE_KINDS:
        issues.append("non_participant_source_provenance")

    source_schema = source.get("response_schema") if isinstance(source.get("response_schema"), dict) else {}
    if source_schema.get("placeholder") is True:
        issues.append("stage3_placeholder_response_schema")

    source_items = [item for item in source.get("items", []) or [] if isinstance(item, dict)]
    runtime_items = [item for item in runtime.get("items", []) or [] if isinstance(item, dict)]
    source_by_id = {
        str(item.get("id") or item.get("data_export_tag")): _participant_item_signature(item)
        for item in source_items
        if item.get("id") or item.get("data_export_tag")
    }
    source_signatures = {
        _participant_item_signature(item)
        for item in source_items
        if _normalized_contract_text(item.get("question"))
    }
    for item in runtime_items:
        item_id = str(item.get("id") or item.get("data_export_tag") or "")
        signature = _participant_item_signature(item)
        id_match = bool(item_id and source_by_id.get(item_id) == signature)
        if not id_match and signature not in source_signatures:
            issues.append("runtime_item_not_derived_from_stage3")
            break
        metadata = item.get("metadata") if isinstance(item.get("metadata"), dict) else {}
        if metadata.get("placeholder") is True:
            issues.append("runtime_item_is_placeholder")
            break

    runtime_instructions = _normalized_contract_text(
        runtime.get("instructions") or runtime.get("stimulus")
    )
    source_instructions = _normalized_contract_text(
        source.get("instructions") or source.get("stimulus")
    )
    source_blocks = {
        _normalized_contract_text(block.get("text"))
        for block in source.get("instruction_blocks", []) or []
        if isinstance(block, dict) and _normalized_contract_text(block.get("text"))
    }
    if runtime_instructions:
        derived_instructions = runtime_instructions == source_instructions
        if not derived_instructions and source_blocks:
            remaining = runtime_instructions
            while remaining:
                prefix = max(
                    (
                        block
                        for block in source_blocks
                        if remaining == block or remaining.startswith(block + " ")
                    ),
                    key=len,
                    default=None,
                )
                if prefix is None:
                    break
                remaining = remaining[len(prefix):].strip()
            derived_instructions = not remaining
        if not derived_instructions:
            issues.append("runtime_instructions_not_derived_from_stage3")

    runtime_conditions = runtime.get("conditions") if isinstance(runtime.get("conditions"), list) else []
    source_conditions = source.get("conditions") if isinstance(source.get("conditions"), list) else []
    if runtime_conditions != source_conditions:
        issues.append("runtime_conditions_not_derived_from_stage3")

    issues = sorted(dict.fromkeys(issues))
    return {
        "valid": not issues,
        "source_ready": source_ready,
        "source_primary": source_primary,
        "issues": issues,
    }


def _read_json_for_audit(path: Path) -> tuple[Optional[Dict[str, Any]], Optional[str]]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return None, "missing"
    except json.JSONDecodeError as exc:
        return None, f"invalid_json:{exc.msg}"
    except Exception as exc:  # pragma: no cover - defensive filesystem guard
        return None, f"{type(exc).__name__}:{exc}"
    if not isinstance(data, dict):
        return None, "json_not_object"
    return data, None


def _iter_ground_truth_findings(ground_truth: Dict[str, Any]) -> List[Dict[str, Any]]:
    findings: List[Dict[str, Any]] = []
    for study in ground_truth.get("studies", []) or []:
        if not isinstance(study, dict):
            continue
        for finding in study.get("findings", []) or []:
            if isinstance(finding, dict):
                findings.append(finding)
    return findings


def _package_file_audit(study_dir: Path) -> tuple[Dict[str, Any], Dict[str, Dict[str, Any]]]:
    required = {}
    loaded: Dict[str, Dict[str, Any]] = {}
    for name in ("metadata.json", "specification.json", "ground_truth.json"):
        path = study_dir / name
        data, error = _read_json_for_audit(path)
        required[name] = {
            "exists": path.exists(),
            "valid_json_object": error is None,
            "error": error,
        }
        if data is not None:
            loaded[name] = data

    materials_dir = study_dir / "materials"
    material_files = sorted(materials_dir.glob("*.json")) if materials_dir.exists() else []
    required["materials/"] = {
        "exists": materials_dir.exists(),
        "json_files": [path.name for path in material_files],
        "count": len(material_files),
    }
    return required, loaded


def _package_reference_audit(
    *,
    metadata: Dict[str, Any],
    specification: Dict[str, Any],
    ground_truth: Dict[str, Any],
    material_ids: set[str],
    material_by_id: Dict[str, Dict[str, Any]],
) -> Dict[str, Any]:
    findings = _iter_ground_truth_findings(ground_truth)
    material_refs = sorted(
        {
            str(finding.get("material_id") or finding.get("sub_study_id"))
            for finding in findings
            if finding.get("material_id") or finding.get("sub_study_id")
        }
    )
    spec_sub_studies = set()
    participants = specification.get("participants") if isinstance(specification.get("participants"), dict) else {}
    by_sub = participants.get("by_sub_study") if isinstance(participants.get("by_sub_study"), dict) else {}
    spec_sub_studies.update(str(key) for key in by_sub.keys())
    scenarios = {
        str(item)
        for item in metadata.get("scenarios", []) or []
        if str(item).strip()
    }
    missing_material_refs = sorted(ref for ref in material_refs if ref not in material_ids)
    unreferenced_materials = sorted(material_ids - set(material_refs)) if material_refs else sorted(material_ids - scenarios)
    missing_spec_refs = sorted(ref for ref in material_refs if spec_sub_studies and ref not in spec_sub_studies)

    target_refs_by_material: Dict[str, List[str]] = {}
    for finding in findings:
        material_ref_raw = finding.get("material_id") or finding.get("sub_study_id")
        target_id_raw = finding.get("target_id")
        if material_ref_raw in (None, "") or target_id_raw in (None, ""):
            continue
        material_ref = str(material_ref_raw).strip()
        target_id = str(target_id_raw).strip()
        if not material_ref or not target_id:
            continue
        target_refs_by_material.setdefault(material_ref, []).append(target_id)
    target_refs_by_material = {
        material_ref: sorted(dict.fromkeys(target_ids))
        for material_ref, target_ids in sorted(target_refs_by_material.items())
    }

    material_target_links: Dict[str, List[str]] = {}
    missing_material_target_links: Dict[str, List[str]] = {}
    for material_ref, target_ids in target_refs_by_material.items():
        material = material_by_id.get(material_ref)
        if not isinstance(material, dict):
            continue
        raw_material_target_ids = material.get("target_ids")
        if isinstance(raw_material_target_ids, list):
            material_target_ids = {
                str(target_id).strip()
                for target_id in raw_material_target_ids
                if target_id not in (None, "") and str(target_id).strip()
            }
        else:
            material_target_ids = set()
        material_target_links[material_ref] = sorted(material_target_ids)
        missing_targets = sorted(set(target_ids) - material_target_ids)
        if missing_targets:
            missing_material_target_links[material_ref] = missing_targets

    return {
        "ground_truth_findings": len(findings),
        "ground_truth_material_refs": material_refs,
        "ground_truth_target_refs_by_material": target_refs_by_material,
        "metadata_scenarios": sorted(scenarios),
        "specification_sub_studies": sorted(spec_sub_studies),
        "missing_material_refs": missing_material_refs,
        "unreferenced_materials": unreferenced_materials,
        "missing_specification_refs": missing_spec_refs,
        "material_target_links": material_target_links,
        "missing_material_target_links": missing_material_target_links,
    }


def _material_file_audit(material_by_id: Dict[str, Dict[str, Any]]) -> Dict[str, Any]:
    by_material: Dict[str, Dict[str, Any]] = {}
    issue_counts: Dict[str, int] = {}
    for material_id, material in material_by_id.items():
        issues = _runtime_material_issues(material)
        for issue in issues:
            issue_counts[issue] = issue_counts.get(issue, 0) + 1
        readiness = material.get("readiness") if isinstance(material.get("readiness"), dict) else {}
        by_material[material_id] = {
            "runtime_issues": issues,
            "readiness": readiness,
            "instruction_chars": len(str(material.get("instructions") or material.get("stimulus") or "")),
            "items": len(material.get("items") or []) if isinstance(material.get("items"), list) else 0,
        }
    return {
        "materials": by_material,
        "issue_counts": issue_counts,
    }


def _build_package_audit(
    *,
    study_id: str,
    study_dir: Path,
    materials_audit: Dict[str, Any],
    material_by_id: Dict[str, Dict[str, Any]],
) -> Dict[str, Any]:
    required_files, loaded = _package_file_audit(study_dir)
    issues: List[Dict[str, Any]] = []

    for name, info in required_files.items():
        if name == "materials/":
            if not info.get("exists"):
                issues.append({"severity": "error", "path": "materials/", "message": "materials directory missing"})
            elif not info.get("count"):
                issues.append({"severity": "error", "path": "materials/", "message": "no material JSON files"})
            continue
        if not info.get("exists"):
            issues.append({"severity": "error", "path": name, "message": "required package file missing"})
        elif not info.get("valid_json_object"):
            issues.append({"severity": "error", "path": name, "message": f"invalid JSON package file: {info.get('error')}"})

    metadata = loaded.get("metadata.json", {})
    specification = loaded.get("specification.json", {})
    ground_truth = loaded.get("ground_truth.json", {})
    for name, payload, key in (
        ("metadata.json", metadata, "id"),
        ("specification.json", specification, "study_id"),
        ("ground_truth.json", ground_truth, "study_id"),
    ):
        if payload and payload.get(key) != study_id:
            issues.append(
                {
                    "severity": "error",
                    "path": f"{name}.{key}",
                    "message": f"package id mismatch: {payload.get(key)!r} != {study_id!r}",
                }
            )

    material_ids = set(material_by_id.keys())
    refs = _package_reference_audit(
        metadata=metadata,
        specification=specification,
        ground_truth=ground_truth,
        material_ids=material_ids,
        material_by_id=material_by_id,
    )
    for ref in refs["missing_material_refs"]:
        issues.append({"severity": "error", "path": "ground_truth.json", "message": f"material reference has no file: {ref}"})
    for ref in refs["missing_specification_refs"]:
        issues.append({"severity": "warning", "path": "specification.json", "message": f"material ref missing from participants.by_sub_study: {ref}"})
    for ref, target_ids in refs["missing_material_target_links"].items():
        issues.append(
            {
                "severity": "error",
                "path": f"materials/{ref}.json.target_ids",
                "message": "ground_truth target_id not covered by material: " + ", ".join(target_ids),
            }
        )

    for material_id, item in materials_audit.get("materials", {}).items():
        derivation = item.get("derivation_contract") if isinstance(item, dict) else {}
        for issue in derivation.get("issues", []) if isinstance(derivation, dict) else []:
            issues.append(
                {
                    "severity": "error",
                    "path": f"materials/{material_id}.json",
                    "message": f"Stage 3 derivation contract failed: {issue}",
                }
            )

    material_file_audit = _material_file_audit(material_by_id)
    for material_id, item in material_file_audit["materials"].items():
        if item["runtime_issues"]:
            issues.append(
                {
                    "severity": "error",
                    "path": f"materials/{material_id}.json",
                    "message": "material runtime issues: " + ", ".join(item["runtime_issues"]),
                }
            )

        material = material_by_id.get(material_id, {})
        coverage = material.get("coverage_ledger") if isinstance(material.get("coverage_ledger"), dict) else {}
        if coverage and coverage.get("ready") is not True:
            issues.append(
                {
                    "severity": "error",
                    "path": f"materials/{material_id}.json.coverage_ledger",
                    "message": "source-grounded instrument coverage failed: "
                    + ", ".join(str(value) for value in coverage.get("blocking_issues", []) or []),
                }
            )
        source_trace = material.get("source_trace") if isinstance(material.get("source_trace"), dict) else {}
        if source_trace.get("extractor") == "pdf_evidence_provider_v1":
            verifier = source_trace.get("semantic_verifier") if isinstance(source_trace.get("semantic_verifier"), dict) else {}
            if verifier.get("status") != "pass":
                issues.append(
                    {
                        "severity": "error",
                        "path": f"materials/{material_id}.json.source_trace.semantic_verifier",
                        "message": f"PDF instrument semantic verifier did not pass: {verifier.get('status')!r}",
                    }
                )

    material_patch_required = bool(materials_audit.get("materials_needing_patch"))
    loadable = not any(
        issue["severity"] == "error"
        for issue in issues
        if not (str(issue["path"]).startswith("materials/") and str(issue["path"]) != "materials/")
    )
    ready_for_simulation = loadable and not material_patch_required and not any(issue["severity"] == "error" for issue in issues)
    return {
        "version": "stage4_package_contract_v1",
        "loadable": loadable,
        "ready_for_simulation": ready_for_simulation,
        "human_patch_required": not ready_for_simulation,
        "required_files": required_files,
        "references": refs,
        "material_files": material_file_audit,
        "issues": issues,
    }


def _build_audit(
    extraction: Dict[str, Any],
    study_id: str,
    study_dir: Path,
    material_paths: List[Path],
) -> Dict[str, Any]:
    source_materials = _canonicalize_material_map(extraction.get("study_materials"))
    material_by_id: Dict[str, Dict[str, Any]] = {}
    for path in material_paths:
        try:
            material = json.loads(Path(path).read_text(encoding="utf-8"))
        except Exception as exc:  # pragma: no cover - defensive audit guard
            material_by_id[Path(path).stem] = {
                "sub_study_id": Path(path).stem,
                "_load_error": f"{type(exc).__name__}: {exc}",
            }
            continue
        if isinstance(material, dict):
            key = canonical_sub_study_id(
                material.get("material_id") or material.get("sub_study_id") or Path(path).stem
            )
            material["sub_study_id"] = key
            if material.get("material_id"):
                material["material_id"] = key
            material_by_id[key] = material

    materials_audit: Dict[str, Any] = {}
    targets = [target for target in extraction.get("simulation_targets", []) or [] if isinstance(target, dict)]
    audit_units: List[Dict[str, Any]] = []
    if targets:
        grouped_targets: Dict[str, List[Dict[str, Any]]] = {}
        for target in targets:
            sub_id = canonical_sub_study_id(target.get("sub_study_id"))
            if sub_id:
                grouped_targets.setdefault(sub_id, []).append(target)
        for sub_id, grouped in grouped_targets.items():
            audit_units.append({"audit_id": sub_id, "sub_study_id": sub_id, "targets": grouped})
    else:
        for study in extraction.get("studies", []):
            for sub_study in study.get("sub_studies", []):
                sub_id = canonical_sub_study_id(sub_study.get("sub_study_id"))
                if sub_id:
                    audit_units.append({"audit_id": sub_id, "sub_study_id": sub_id, "targets": []})

    for unit in audit_units:
        audit_id = unit["audit_id"]
        sub_id = unit["sub_study_id"]
        runtime = material_by_id.get(audit_id, {})
        source = source_materials.get(sub_id)
        source = source if isinstance(source, dict) else {}
        source_readiness = source.get("readiness") if isinstance(source.get("readiness"), dict) else {}
        runtime_readiness = runtime.get("readiness") if isinstance(runtime.get("readiness"), dict) else {}
        runtime_issues = _runtime_material_issues(runtime)
        derivation_contract = _material_derivation_contract(runtime, source or None)
        source_ready = source_readiness.get("ready") is True
        runtime_ready = runtime_readiness.get("ready") is True
        ready = source_ready and runtime_ready and not runtime_issues and derivation_contract["valid"]
        material_path = study_dir / "materials" / f"{audit_id}.json"
        materials_audit[audit_id] = {
            "ready": ready,
            "human_patch_required": not ready,
            "runtime_material": str(material_path),
            "runtime_issues": runtime_issues,
            "runtime_readiness": runtime_readiness,
            "source_readiness": source_readiness,
            "derivation_contract": derivation_contract,
            "selection": source.get("selection", {}),
            "targets": unit.get("targets", []),
            "target_ids": [
                str(target.get("target_id"))
                for target in unit.get("targets", [])
                if isinstance(target, dict) and target.get("target_id")
            ],
            "sub_study_id": sub_id,
            "source_trace": source.get("source_trace", {}),
            "human_material_contract": source.get("human_material_contract", {}),
            "field_evidence": (
                source.get("human_material_contract", {}).get("field_evidence", {})
                if isinstance(source.get("human_material_contract"), dict)
                else {}
            ),
            "conditions": source.get("conditions", []),
            "response_schema": source.get("response_schema", {}),
            "counts": {
                "instruction_chars": len(str(runtime.get("instructions") or runtime.get("stimulus") or "")),
                "items": len(runtime.get("items") or []) if isinstance(runtime.get("items"), list) else 0,
            },
        }

    ready_count = sum(1 for item in materials_audit.values() if item["ready"])
    material_package_audit = {
        "materials_total": len(materials_audit),
        "materials_ready": ready_count,
        "materials_needing_patch": len(materials_audit) - ready_count,
        "materials": materials_audit,
    }
    package_audit = _build_package_audit(
        study_id=study_id,
        study_dir=study_dir,
        materials_audit=material_package_audit,
        material_by_id=material_by_id,
    )
    return {
        "stage4_version": "human-study-bench-draft",
        "study_id": study_id,
        "source_schema": extraction.get("source_schema"),
        "materials_total": len(materials_audit),
        "materials_ready": ready_count,
        "materials_needing_patch": len(materials_audit) - ready_count,
        "materials": materials_audit,
        "package_audit": package_audit,
    }


def _update_registry(data_dir: Path, metadata: Dict[str, Any]) -> Path:
    registry_path = data_dir / "registry.json"
    if registry_path.exists():
        registry = json.loads(registry_path.read_text(encoding="utf-8"))
    else:
        registry = {"version": "0.1.0", "last_updated": None, "total_studies": 0, "studies": []}

    studies = [item for item in registry.get("studies", []) if item.get("id") != metadata["id"]]
    studies.append(
        {
            "id": metadata["id"],
            "title": metadata.get("title", ""),
            "domain": metadata.get("domain"),
            "subdomain": metadata.get("subdomain"),
            "difficulty": metadata.get("difficulty", "medium"),
            "tags": metadata.get("keywords", []),
            "status": "active",
            "added_date": date.today().isoformat(),
            "version": "1.0",
            "estimated_time_minutes": 10,
        }
    )
    registry["studies"] = sorted(studies, key=lambda item: item.get("id", ""))
    registry["total_studies"] = len(registry["studies"])
    registry["last_updated"] = date.today().isoformat()
    _write_json(registry_path, registry)
    return registry_path


def _build_json_package(
    extraction: Dict[str, Any],
    study_id: str,
    study_dir: Path,
    *,
    use_llm: bool,
    provider: str,
    model: str,
    api_key: Optional[str],
    api_base: Optional[str],
    pdf_path: Optional[Path],
    selection_llm_client: Any = None,
) -> Dict[str, Any]:
    metadata = _deterministic_metadata(extraction, study_id)
    specification = _deterministic_specification(extraction, study_id)
    ground_truth = _deterministic_ground_truth(extraction, study_id)
    json_generation = "deterministic_contracts"
    if use_llm:
        try:
            generator = JSONGenerator(provider=provider, model=model, api_key=api_key, api_base=api_base)
            print("  Stage 4 enriching metadata domain/keywords", flush=True)
            enrichment = generator.generate_metadata(
                _metadata_enrichment_input(extraction),
                study_id,
                pdf_path=None,
            )
            for key in ("domain", "subdomain", "keywords"):
                value = enrichment.get(key)
                if value not in (None, "", [], {}):
                    metadata[key] = value
            json_generation = "deterministic_contracts_llm_metadata"
        except Exception as exc:
            print(f"Warning: Stage 4 metadata enrichment failed; using deterministic metadata: {exc}")

    print("  Stage 4 writing deterministic metadata/specification/ground_truth contracts", flush=True)
    material_paths = _deterministic_materials(extraction, study_dir, selection_llm_client=selection_llm_client)
    _write_json(study_dir / "metadata.json", metadata)
    _write_json(study_dir / "specification.json", specification)
    _write_json(study_dir / "ground_truth.json", ground_truth)
    return {
        "metadata": metadata,
        "specification": specification,
        "ground_truth": ground_truth,
        "material_paths": material_paths,
        "json_generation": json_generation,
    }


def _metadata_enrichment_input(extraction: Dict[str, Any]) -> Dict[str, Any]:
    studies: List[Dict[str, Any]] = []
    for study in extraction.get("studies", []) or []:
        if not isinstance(study, dict):
            continue
        studies.append(
            {
                "study_id": study.get("study_id"),
                "study_name": study.get("study_name"),
                "phenomenon": study.get("phenomenon"),
                "effects": [
                    {
                        "IV": effect.get("IV"),
                        "DV": effect.get("DV"),
                        "effecttype": effect.get("effecttype"),
                    }
                    for effect in study.get("effects", []) or []
                    if isinstance(effect, dict)
                ],
                "sub_studies": [
                    {"sub_study_id": sub.get("sub_study_id")}
                    for sub in study.get("sub_studies", []) or []
                    if isinstance(sub, dict) and sub.get("sub_study_id")
                ],
            }
        )
    return {
        "paper_title": extraction.get("paper_title"),
        "paper_abstract": extraction.get("paper_abstract"),
        "studies": studies,
    }


def build_human_study_package(
    json_path: Path,
    *,
    data_dir: Path = Path("data"),
    study_dir: Optional[Path] = None,
    study_id: Optional[str] = None,
    pdf_path: Optional[Path] = None,
    provider: str = "openai",
    model: str = "gpt-4o-mini",
    api_key: Optional[str] = None,
    api_base: Optional[str] = None,
    use_llm: bool = False,
    selection_llm_client: Any = None,
    generate_config: bool = False,
    config_dir: Path = Path("src/studies"),
    update_registry: bool = True,
    hub_layout: bool = False,
) -> Dict[str, Any]:
    json_path = Path(json_path)
    data_dir = Path(data_dir)
    payload = json.loads(json_path.read_text(encoding="utf-8"))
    resolved_study_id = study_id or _default_study_id(payload, json_path)
    extraction = normalize_to_human_extraction(payload)
    extraction["study_id"] = resolved_study_id

    if hub_layout:
        study_root = Path(study_dir) if study_dir else data_dir / resolved_study_id
        package_dir = study_root / "source"
    else:
        study_root = Path(study_dir) if study_dir else data_dir / "studies" / resolved_study_id
        package_dir = study_root

    study_root.mkdir(parents=True, exist_ok=True)
    package_dir.mkdir(parents=True, exist_ok=True)
    source_path = _write_json(package_dir / "source_extraction.json", extraction)

    package = _build_json_package(
        extraction,
        resolved_study_id,
        package_dir,
        use_llm=use_llm,
        provider=provider,
        model=model,
        api_key=api_key,
        api_base=api_base,
        pdf_path=pdf_path,
        selection_llm_client=selection_llm_client,
    )
    audit = _build_audit(extraction, resolved_study_id, package_dir, package["material_paths"])
    audit_path = _write_json(package_dir / "audit.json", audit)

    registry_path = None if hub_layout else (_update_registry(data_dir, package["metadata"]) if update_registry else None)
    hub_files: List[Path] = []
    if hub_layout:
        hub_files.extend(_write_hub_root_files(study_root, package["metadata"], extraction, audit))
        hub_files.extend(_write_hub_scripts(study_root, resolved_study_id))
        if pdf_path and Path(pdf_path).exists():
            pdf_dest = package_dir / Path(pdf_path).name
            if Path(pdf_path).resolve() != pdf_dest.resolve():
                shutil.copy2(pdf_path, pdf_dest)
            hub_files.append(pdf_dest)

    expected_config_path = (
        study_root / "scripts" / "config.py"
        if hub_layout
        else config_dir / f"{resolved_study_id}_config.py"
    )
    config_path = None
    config_status = "skipped"
    config_error = None
    if generate_config:
        if not api_key:
            config_status = "skipped_no_llm"
        else:
            config_path = expected_config_path
            try:
                print(f"  Stage 4 generating StudyConfig adapter: {config_path}", flush=True)
                ConfigGenerator(provider=provider, model=model, api_key=api_key, api_base=api_base).generate(
                    extraction,
                    resolved_study_id,
                    config_path,
                    pdf_path=pdf_path,
                    study_dir=package_dir,
                    standalone=hub_layout,
                )
                config_status = "generated"
            except Exception as exc:
                config_path = None
                config_status = "failed"
                config_error = str(exc)

    adapter_validation: Dict[str, Any] = {}
    adapter_ready = False
    if config_status == "generated":
        adapter_ready, validation_error, adapter_validation = _validate_study_config_adapter(
            expected_config_path,
            study_root=study_root,
            package_dir=package_dir,
            material_ids=[path.stem for path in package["material_paths"]],
            hub_layout=hub_layout,
        )
        if not adapter_ready:
            config_status = "failed_validation"
            config_error = validation_error
    package_audit = audit.setdefault("package_audit", {})
    package_audit["adapter"] = {
        "required": True,
        "ready": adapter_ready,
        "path": str(expected_config_path),
        "generation_status": config_status,
        "error": config_error,
        "validation": adapter_validation,
    }
    if not adapter_ready:
        issues = package_audit.setdefault("issues", [])
        if not any(
            issue == "study_config_adapter_unavailable"
            or (
                isinstance(issue, dict)
                and issue.get("code") == "study_config_adapter_unavailable"
            )
            for issue in issues
        ):
            issues.append(
                {
                    "severity": "error",
                    "path": "scripts/config.py",
                    "code": "study_config_adapter_unavailable",
                    "message": config_error
                    or f"StudyConfig adapter generation status is {config_status!r}.",
                }
            )
        package_audit["ready_for_simulation"] = False
        package_audit["human_patch_required"] = True
    _write_json(audit_path, audit)
    if hub_layout:
        _write_hub_root_files(study_root, package["metadata"], extraction, audit)

    generated_files = [
        source_path,
        package_dir / "metadata.json",
        package_dir / "specification.json",
        package_dir / "ground_truth.json",
        audit_path,
        *package["material_paths"],
        *hub_files,
    ]
    if registry_path:
        generated_files.append(registry_path)
    if config_path:
        generated_files.append(config_path)

    return {
        "stage4_version": "human-study-bench",
        "study_id": resolved_study_id,
        "source_json": str(json_path),
        "data_dir": str(data_dir),
        "study_dir": str(study_root),
        "source_dir": str(package_dir),
        "hub_layout": hub_layout,
        "registry_path": str(registry_path) if registry_path else None,
        "audit_path": str(audit_path),
        "config_path": str(config_path) if config_path else None,
        "config_status": config_status,
        "config_error": config_error,
        "json_generation": package["json_generation"],
        "generated_files": [str(path) for path in generated_files],
    }


def _python_source_is_valid(path: Path) -> bool:
    try:
        ast.parse(path.read_text(encoding="utf-8"))
    except (OSError, SyntaxError, UnicodeDecodeError):
        return False
    return True


def _validate_study_config_adapter(
    config_path: Path,
    *,
    study_root: Path,
    package_dir: Path,
    material_ids: List[str],
    hub_layout: bool,
) -> tuple[bool, Optional[str], Dict[str, Any]]:
    """Import and exercise a generated adapter in an isolated Python process."""
    config_path = Path(config_path).resolve()
    study_root = Path(study_root).resolve()
    package_dir = Path(package_dir).resolve()
    if not config_path.is_file() or not _python_source_is_valid(config_path):
        return False, "Generated StudyConfig is missing or invalid Python.", {}

    smoke_script = r'''
import copy
import importlib.util
import json
import re
import sys
from pathlib import Path

config_path = Path(sys.argv[1])
study_root = Path(sys.argv[2])
package_dir = Path(sys.argv[3])
expected_material_ids = set(json.loads(sys.argv[4]))
hub_layout = sys.argv[5] == "1"

if hub_layout:
    sys.path.insert(0, str(config_path.parent))
else:
    sys.path.insert(0, str(Path.cwd()))

specification = json.loads((package_dir / "specification.json").read_text(encoding="utf-8"))
specification = copy.deepcopy(specification)
participants = specification.setdefault("participants", {})
participants["n"] = 1
for value in (participants.get("by_sub_study") or {}).values():
    if isinstance(value, dict):
        value["n"] = 1

module_spec = importlib.util.spec_from_file_location("generated_study_config", config_path)
if module_spec is None or module_spec.loader is None:
    raise RuntimeError("could not load generated config module")
module = importlib.util.module_from_spec(module_spec)
module_spec.loader.exec_module(module)
config_classes = [
    value
    for value in vars(module).values()
    if isinstance(value, type)
    and value.__module__ == module.__name__
    and value.__name__.endswith("Config")
    and callable(getattr(value, "create_trials", None))
]
if len(config_classes) != 1:
    raise RuntimeError(f"expected one generated StudyConfig class, found {len(config_classes)}")

config = config_classes[0](study_root, specification)
original_load_material = config.load_material
loaded_materials = {}

def tracked_load_material(material_id):
    value = original_load_material(material_id)
    loaded_materials[str(material_id)] = value
    return value

config.load_material = tracked_load_material
probe_trial_count = max(1, len(expected_material_ids))
trials = config.create_trials(n_trials=probe_trial_count)
if not isinstance(trials, list) or not trials:
    raise RuntimeError(
        f"create_trials(n_trials={probe_trial_count}) returned no trials"
    )
if len(trials) != probe_trial_count:
    raise RuntimeError(
        f"create_trials(n_trials={probe_trial_count}) returned {len(trials)} trials; "
        "n_trials must be a total package-level budget"
    )
if len(trials) > max(100, len(expected_material_ids) * 20):
    raise RuntimeError(f"smoke run produced an unreasonable {len(trials)} trials")
missing_loads = expected_material_ids - set(loaded_materials)
if missing_loads:
    raise RuntimeError("adapter did not load materials: " + ", ".join(sorted(missing_loads)))

covered_materials = set()
prompt_summaries = []
prompt_builder = config.get_prompt_builder()
for trial_index, trial in enumerate(trials):
    if not isinstance(trial, dict):
        raise RuntimeError(f"trial {trial_index} is not an object")
    material_id = next(
        (
            str(trial.get(key))
            for key in ("sub_study_id", "material_id", "scenario_id", "scenario")
            if str(trial.get(key) or "") in expected_material_ids
        ),
        "",
    )
    if material_id:
        covered_materials.add(material_id)
    runtime_payload = trial.get("material") if isinstance(trial.get("material"), dict) else trial
    trial_items = runtime_payload.get("items")
    if not isinstance(trial_items, list) or not trial_items:
        raise RuntimeError(f"trial {trial_index} has no executable items")

    if material_id and isinstance(loaded_materials.get(material_id), dict):
        source_items = [
            value
            for value in loaded_materials[material_id].get("items", []) or []
            if isinstance(value, dict)
        ]
        source_by_unit = {}
        for item in source_items:
            condition = item.get("condition") if isinstance(item.get("condition"), dict) else {}
            unit_id = str(condition.get("runtime_unit_id") or item.get("runtime_unit_id") or "")
            if unit_id:
                source_by_unit.setdefault(unit_id, set()).add(str(item.get("id") or ""))
        trial_by_unit = {}
        for item in trial_items:
            if not isinstance(item, dict):
                continue
            condition = item.get("condition") if isinstance(item.get("condition"), dict) else {}
            unit_id = str(condition.get("runtime_unit_id") or item.get("runtime_unit_id") or "")
            if unit_id:
                trial_by_unit.setdefault(unit_id, set()).add(str(item.get("id") or ""))
        for unit_id, selected_ids in trial_by_unit.items():
            expected_ids = source_by_unit.get(unit_id, set())
            if expected_ids and not expected_ids.issubset(selected_ids):
                missing_ids = expected_ids - selected_ids
                raise RuntimeError(
                    f"trial {trial_index} cropped runtime unit {unit_id}: "
                    + ", ".join(sorted(missing_ids))
                )

    prompt = prompt_builder.build_trial_prompt(trial)
    if not isinstance(prompt, str) or not prompt.strip():
        raise RuntimeError(f"trial {trial_index} produced an empty prompt")
    response_spec_headers = re.findall(r"(?mi)^\s*RESPONSE_SPEC\s*:", prompt)
    if len(response_spec_headers) != 1 or "no response fields detected" in prompt.lower():
        raise RuntimeError(f"trial {trial_index} has an invalid RESPONSE_SPEC")
    prompt_summaries.append(
        {
            "material_id": material_id,
            "item_count": len(trial_items),
            "prompt_chars": len(prompt),
        }
    )

missing_trials = expected_material_ids - covered_materials
if missing_trials:
    raise RuntimeError("adapter produced no trial for materials: " + ", ".join(sorted(missing_trials)))

summary = {
    "status": "pass",
    "trial_count": len(trials),
    "loaded_material_ids": sorted(loaded_materials),
    "prompt_summaries": prompt_summaries[:20],
}
print("ADAPTER_SMOKE_JSON=" + json.dumps(summary, ensure_ascii=False))
'''
    try:
        completed = subprocess.run(
            [
                sys.executable,
                "-c",
                smoke_script,
                str(config_path),
                str(study_root),
                str(package_dir),
                json.dumps(sorted(set(material_ids))),
                "1" if hub_layout else "0",
            ],
            cwd=str(_repo_root()),
            capture_output=True,
            text=True,
            timeout=60,
            check=False,
        )
    except subprocess.TimeoutExpired:
        return False, "Generated StudyConfig smoke test exceeded 60 seconds.", {}
    if completed.returncode != 0:
        detail = (completed.stderr or completed.stdout or "unknown adapter error").strip()
        return False, f"Generated StudyConfig smoke test failed: {detail[-2000:]}", {}
    marker = "ADAPTER_SMOKE_JSON="
    line = next(
        (value for value in reversed(completed.stdout.splitlines()) if value.startswith(marker)),
        "",
    )
    if not line:
        return False, "Generated StudyConfig smoke test returned no validation summary.", {}
    try:
        summary = json.loads(line[len(marker):])
    except json.JSONDecodeError as exc:
        return False, f"Generated StudyConfig smoke summary was invalid JSON: {exc}", {}
    return True, None, summary


