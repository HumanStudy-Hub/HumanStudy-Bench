def _effect_reported_statistics(effect: Dict[str, Any]) -> str:
    stats = effect.get("stats") if isinstance(effect.get("stats"), dict) else {}
    parts: List[str] = []
    for key in ("B", "b", "t", "f", "z", "chi_square", "D", "eta_square", "p_value", "sig"):
        value = stats.get(key)
        if value not in (None, "", [None, None]):
            parts.append(f"{key}={value}")
    ci = stats.get("ci")
    if isinstance(ci, list) and any(item is not None for item in ci):
        parts.append(f"ci={ci}")
    return ", ".join(parts)


def _effect_to_statistical_result(effect: Dict[str, Any], index: int) -> Dict[str, Any]:
    claim = effect.get("claim") or effect.get("IV") or effect.get("DV") or f"Effect {index}"
    hypothesis = effect.get("statistical_hypothesis") or f"{effect.get('IV')} -> {effect.get('DV')}"
    test_name = effect.get("effecttype") or "reported_effect"
    return {
        "claim": claim,
        "hypothesis": hypothesis,
        "test_name": test_name,
        "statistical_hypothesis": hypothesis,
        "reported_statistics": _effect_reported_statistics(effect),
        "significance_level": 0.05,
        "expected_direction": effect.get("direction") or "none",
        "original_effect": effect,
    }


