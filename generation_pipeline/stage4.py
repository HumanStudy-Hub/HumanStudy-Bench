def _deterministic_materials(
    extraction: Dict[str, Any],
    study_dir: Path,
    *,
    selection_llm_client: Any = None,
) -> List[Path]:
    materials_dir = study_dir / "materials"
    materials_dir.mkdir(parents=True, exist_ok=True)
    for old_json in materials_dir.glob("*.json"):
        old_json.unlink()
    paths: List[Path] = []
    targets = [target for target in extraction.get("simulation_targets", []) or [] if isinstance(target, dict)]
    source_materials = extraction.get("study_materials") if isinstance(extraction.get("study_materials"), dict) else {}
    if targets:
        by_sub_study: Dict[str, List[Dict[str, Any]]] = {}
        for rank, target in enumerate(targets, start=1):
            sub_id = str(target.get("sub_study_id") or "")
            if not sub_id:
                continue
            target.setdefault("target_id", f"{sub_id}__effect_{rank:02d}")
            by_sub_study.setdefault(sub_id, []).append(target)

        for sub_id, sub_targets in by_sub_study.items():
            effects: List[Dict[str, Any]] = []
            study_name = sub_id
            for target in sub_targets:
                effect, _, study, _ = _target_effect(extraction, target)
                if effect:
                    effects.append(effect)
                study_name = str(target.get("study_name") or study.get("study_name") or study.get("study_id") or study_name)
            base_material = source_materials.get(sub_id) if isinstance(source_materials.get(sub_id), dict) else None
            material = _study_prompt_material(
                sub_id=sub_id,
                study_name=study_name,
                effects=effects,
                targets=sub_targets,
                base_material=base_material,
                selection_llm_client=selection_llm_client,
            )
            path = materials_dir / f"{sub_id}.json"
            path.write_text(json.dumps(material, indent=2, ensure_ascii=False), encoding="utf-8")
            paths.append(path)
        return paths

    for study in extraction.get("studies", []):
        for sub_study in study.get("sub_studies", []):
            sub_id = sub_study.get("sub_study_id")
            if not sub_id:
                continue
            source_material = source_materials.get(sub_id) if isinstance(source_materials.get(sub_id), dict) else None
            items = sub_study.get("items") if isinstance(sub_study.get("items"), list) else []
            instructions = sub_study.get("instructions") or sub_study.get("content") or ""
